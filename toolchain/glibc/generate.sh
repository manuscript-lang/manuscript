#!/bin/sh
# Regenerates the glibc symbol tables (`toolchain/glibc/<arch>.symbols`) that `ms` builds its link-time
# libc stubs from. Each line is `<soname> <version> <symbol> <F|D> [<size>]`: the newest version of the
# symbol that glibc `$version` exports, from the library that a program built against that release links.
# Libraries are searched in the order below, so a symbol that libc and libpthread both export binds in
# libc. Data symbols keep their size for copy relocations. The source is glibc's own ABI lists.
set -eu
version=2.28
here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
for arch in x86_64 aarch64; do
    case $arch in x86_64) dir=x86_64/64 ld=ld-linux-x86-64.so.2 ;; aarch64) dir=aarch64 ld=ld-linux-aarch64.so.1 ;; esac
    : > "$work/seen"
    out=$here/$arch.symbols
    {
        echo "# glibc $version ABI for $arch, generated by toolchain/glibc/generate.sh; do not edit."
        for pair in libc:libc.so.6 libm:libm.so.6 libpthread:libpthread.so.0 libdl:libdl.so.2 librt:librt.so.1 ld:$ld; do
            list=${pair%%:*}
            soname=${pair#*:}
            curl --fail --location --retry 3 -sS \
                "https://raw.githubusercontent.com/bminor/glibc/glibc-$version/sysdeps/unix/sysv/linux/$dir/$list.abilist" |
                awk '$3 != "A"' | sort -k2,2 -k1,1V |
                awk -v so="$soname" -v seen="$work/seen" '
                    BEGIN { while ((getline name < seen) > 0) bound[name] = 1 }
                    !($2 in bound) { last[$2] = so " " $0 }
                    END { for (s in last) print last[s] }' |
                sort -k3,3 > "$work/lib"
            cat "$work/lib"
            awk '{ print $3 }' "$work/lib" >> "$work/seen"
        done
    } > "$out.tmp"
    mv "$out.tmp" "$out"
done
