// docgen captures the implemented standard library from bundled standard-library declarations.
package docgen

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/manuscript-lang/manuscript/pkg/checker"
)

func RenderModule(module checker.APIModule) string {
	return renderModule(module, false)
}

func declarationKind(kind string) string {
	switch kind {
	case "fn":
		return "Function"
	case "record":
		return "Record"
	case "alternative":
		return "Alternative"
	case "interface":
		return "Interface"
	case "type":
		return "Type"
	case "native":
		return "Native type"
	default:
		return kind
	}
}

func renderModule(module checker.APIModule, forSite bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", module.Path)
	if module.Path == "prelude" {
		b.WriteString("Names available in every module; no import required.\n\n")
	} else if module.Path == "@std/optional.ms" || module.Path == "@std/result.ms" || module.Path == "@std/errors.ms" || module.Path == "@std/equality.ms" {
		b.WriteString("These names are available in the prelude; no import required.\n\n")
		fmt.Fprintf(&b, "Explicit imports with `import Name from %q` remain supported.\n\n", module.Path)
	} else if strings.HasPrefix(module.Path, "@std/") {
		fmt.Fprintf(&b, "Import each required symbol with `import Name from %q`.\n\n", module.Path)
	}
	for _, d := range module.Declarations {
		kind := declarationKind(d.Kind)
		// Native types with receiver signatures share the checker's interface
		// representation, but their source declaration remains a type.
		if d.Kind == "interface" && strings.HasPrefix(d.Declaration, "type ") {
			kind = "Native type"
		}
		if forSite {
			fmt.Fprintf(&b, "## %s {data-api-kind=%q}\n\n", d.Name, kind)
		} else {
			fmt.Fprintf(&b, "## %s\n\n**%s**\n\n", d.Name, kind)
		}
		if d.Declaration == "" {
			if forSite {
				b.WriteString("See [special call rules](../call-rules.md).\n\n")
			} else {
				b.WriteString("See [special call rules](#special-call-rules).\n\n")
			}
			continue
		}
		if d.Doc != "" {
			fmt.Fprintf(&b, "%s\n\n", d.Doc)
		}
		fmt.Fprintf(&b, "```manuscript\n%s```\n\n", d.Declaration)
		for _, implementation := range d.ImplementationDeclarations {
			fmt.Fprintf(&b, "```manuscript\n%s```\n\n", implementation)
		}
		if module.Path == "@std/process.ms" && (d.Name == "ProcessControl" || d.Name == "SignalStream") {
			b.WriteString("`watch_signals` observes signals without claiming them. SIGINT/SIGTERM still cancel the native application; `next()` and code following it have no shutdown guarantee. Register `with`/`Closeable` cleanup and finish shutdown work directly in the shielded close call after joining cancelled workers.\n\n")
			if forSite {
				b.WriteString("See the [shutdown cookbook](../../concurrency/shutdown.md) for runnable examples and limitations.\n\n")
			}
		}
	}
	return b.String()
}

func SiteFiles() (map[string][]byte, error) {
	modules := checker.StandardLibrary()
	files := map[string][]byte{}
	var index, full strings.Builder
	index.WriteString("+++\ntitle = \"API reference\"\nweight = 2\n+++\n\n# Standard library API reference\n\nLook up types, functions, and import paths in the bundled standard library. These declarations are generated from source and omit implementation bodies.\n\n[Plain Markdown](/stdlib.md) · [Structured JSON](/stdlib.json) · [LLM index](/llms.txt)\n\nSee [special call rules](../call-rules.md) for constructors, generic receiver methods, and optional arguments.\n\n")
	full.WriteString(StandardLibraryMarkdown())
	files["documentation/standard-library/call-rules.md"] = []byte(callRules)
	for _, module := range modules {
		name := strings.TrimSuffix(strings.TrimPrefix(module.Path, "@std/"), ".ms")
		body := renderModule(module, true)
		files["documentation/standard-library/reference/"+name+".md"] = []byte(fmt.Sprintf("+++\ntitle = %q\n+++\n\n", name) + body)
		fmt.Fprintf(&index, "- [%s](%s.md)\n", module.Path, name)
	}
	files["documentation/standard-library/reference/_index.md"] = []byte(index.String())
	files["website/static/stdlib.md"] = []byte(full.String())
	data, err := JSON(modules)
	if err != nil {
		return nil, err
	}
	files["website/static/stdlib.json"] = data
	return files, nil
}

//go:embed call-rules.md
var callRules string

func StandardLibraryMarkdown() string {
	var b strings.Builder
	b.WriteString("# Manuscript implemented standard library\n\nGenerated by ms doc --stdlib from bundled standard-library declarations.\n\n")
	b.WriteString(strings.SplitN(callRules, "+++", 3)[2])
	b.WriteString("\n")
	for _, module := range checker.StandardLibrary() {
		b.WriteString(RenderModule(module))
	}
	return b.String()
}

func JSON(modules []checker.APIModule) ([]byte, error) {
	data, err := json.MarshalIndent(struct {
		Format  int                 `json:"format"`
		Modules []checker.APIModule `json:"modules"`
	}{1, modules}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
