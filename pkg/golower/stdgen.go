// StandardRuntime generates the Go declarations the runtime package must hold
// for the native standard library: a Go type for every standard record,
// sum type, and contract, and for every native function, operation, and
// implementation a compile-time check that the runtime defines it with exactly
// the signature the lowering calls. The runtime's native types (List, Map,
// Decimal, ...) and its functions are written by hand; this file keeps them
// complete and consistent with the .ms declarations.
func StandardRuntime() (string, error) {
	inv := checker.StandardInventory()
	g := &gen{types: map[string]*typeDecl{}, funcs: map[string]*funcDecl{}, inRuntime: true}
	file := &ast.File{Name: ident("rt")}
	var decls []ast.Decl
	handWritten := map[string]bool{}
	for _, s := range inv.Types {
		t := s.Type
		switch {
		case skippedStandardType(s):
			continue
		case t.Kind == "native" || t.ID == "@std/Optional" || t.ID == "@std/Result":
			handWritten[t.ID] = true
			decls = append(decls, g.standardPresence(s))
		case t.Kind == "record":
			decls = append(decls, g.standardRecord(s))
		case t.Kind == "alternative":
			decls = append(decls, g.standardAlternative(s)...)
		case t.Kind == "contract":
			decls = append(decls, g.standardContract(s))
		}
	}
	for _, s := range inv.Functions {
		decls = append(decls, g.standardFunctionCheck(s))
	}
	for _, op := range inv.Operations {
		if skippedOperation(op) {
			continue
		}
		decls = append(decls, g.standardOperationCheck(op))
	}
	for _, m := range inv.Implementations {
		decls = append(decls, g.standardImplementationCheck(m))
	}
	if g.err != nil {
		return "", g.err
	}
	file.Decls = decls
	text, err := g.printGo(file)
	if err != nil {
		return "", err
	}
	text = regexp.MustCompile(`\brt\.`).ReplaceAllString(text, "")
	return "// Code generated by golower.StandardRuntime from the standard declarations. DO NOT EDIT.\n\n" + text + "\n", nil
}

// skippedStandardType reports declarations that describe properties or
// intrinsic receivers rather than runtime types.
func skippedStandardType(s *checker.Symbol) bool {
	switch s.Name {
	case "Equal", "Hashable", "ValueOperations", "CloneOperations", "StringOperations", "IntOperations", "FloatOperations":
		return true
	}
	return false
}

func skippedOperation(op checker.NativeOperation) bool {
	return op.Receiver.ID == "@std/Optional" && false
}

// typeParams renders type variables as a Go type parameter list.
func (g *gen) typeParams(vars []*checker.Type) *ast.FieldList {
	if len(vars) == 0 {
		return nil
	}
	list := &ast.FieldList{}
	for _, v := range vars {
		constraint := "any"
		for _, b := range v.Bounds {
			if isStd(b, "Hashable") {
				constraint = "comparable"
			}
		}
		list.List = append(list.List, &ast.Field{Names: []*ast.Ident{ident(v.Name)}, Type: ident(constraint)})
	}
	return list
}

func (g *gen) standardPresence(s *checker.Symbol) ast.Decl {
	name := "check_" + s.Name
	spec := &ast.TypeSpec{Name: ident(name), TypeParams: g.typeParams(s.Variables), Assign: 1, Type: g.stdTypeReference(s.Type)}
	return &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}
}

func (g *gen) stdTypeReference(t *checker.Type) ast.Expr {
	var args []ast.Expr
	for _, v := range t.Def.Variables {
		args = append(args, ident(v.Name))
	}
	typ := generic(ident(strings.TrimPrefix(t.ID, "@std/")), args...)
	if t.Kind == "record" || t.Kind == "native" {
		return pointerTo(typ)
	}
	return typ
}

func (g *gen) standardRecord(s *checker.Symbol) ast.Decl {
	var fields []*ast.Field
	for _, f := range s.Type.Def.Fields {
		fields = append(fields, field(camel(f.Name), g.goType(f.Type)))
	}
	spec := &ast.TypeSpec{Name: ident(s.Name), TypeParams: g.typeParams(s.Variables), Type: &ast.StructType{Fields: &ast.FieldList{List: fields}}}
	return &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}
}

func (g *gen) standardAlternative(s *checker.Symbol) []ast.Decl {
	marker := "is" + s.Name
	iface := &ast.TypeSpec{Name: ident(s.Name), TypeParams: g.typeParams(s.Variables), Type: &ast.InterfaceType{Methods: &ast.FieldList{List: []*ast.Field{
		{Names: []*ast.Ident{ident(marker)}, Type: functionType(nil, nil)},
	}}}}
	decls := []ast.Decl{&ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{iface}}}
	for _, c := range s.Type.Def.Cases {
		var fields []*ast.Field
		for _, f := range c.Fields {
			fields = append(fields, field(camel(f.Name), g.goType(f.Type)))
		}
		name := s.Name + "_" + sanitize(c.Name)
		spec := &ast.TypeSpec{Name: ident(name), TypeParams: g.typeParams(s.Variables), Type: &ast.StructType{Fields: &ast.FieldList{List: fields}}}
		decls = append(decls, &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}})
		var args []ast.Expr
		for _, v := range s.Variables {
			args = append(args, ident(v.Name))
		}
		recv := generic(ident(name), args...)
		decls = append(decls, &ast.FuncDecl{Recv: &ast.FieldList{List: []*ast.Field{{Type: recv}}}, Name: ident(marker), Type: functionType(nil, nil), Body: block()})
	}
	return decls
}

func (g *gen) standardContract(s *checker.Symbol) ast.Decl {
	var methods []*ast.Field
	for _, op := range s.Type.Def.Operations {
		if len(checkerOperationVariables(s, op)) > 0 {
			g.fail("contract operation %s.%s has type variables, which a Go interface method cannot", s.Name, op.Name)
		}
		methods = append(methods, &ast.Field{Names: []*ast.Ident{ident(camel(op.Name))}, Type: g.operationType(op.Type)})
	}
	spec := &ast.TypeSpec{Name: ident(s.Name), TypeParams: g.typeParams(s.Variables), Type: &ast.InterfaceType{Methods: &ast.FieldList{List: methods}}}
	return &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}
}

func checkerOperationVariables(s *checker.Symbol, op checker.Operation) []*checker.Type {
	n, ok := checker.NativeOperationFor(s.Type, op.Name)
	if !ok {
		return nil
	}
	return n.Variables
}

// capabilityFields are the leading parameters that supply Equal and Hashable.
func (g *gen) capabilityFields(caps []checker.Capability) []*ast.Field {
	var out []*ast.Field
	for _, c := range caps {
		name := "eq_" + c.Variable.Name
		var typ ast.Expr = generic(rtName("Eq"), ident(c.Variable.Name))
		if c.Property == "Hashable" {
			name = "key_" + c.Variable.Name
			typ = pointerTo(generic(rtName("Hasher"), ident(c.Variable.Name)))
		}
		out = append(out, field(name, typ))
	}
	return out
}

// functionCheck emits `func check_Name[...]() { var _ func(...) R = Name[...] }`.
func (g *gen) functionCheck(name string, vars []*checker.Type, params []*ast.Field, result ast.Expr, target ast.Expr) ast.Decl {
	fn := &ast.FuncType{Params: &ast.FieldList{List: unnamed(params)}, Results: &ast.FieldList{List: []*ast.Field{{Type: result}}}}
	spec := &ast.ValueSpec{Names: []*ast.Ident{ident("_")}, Type: fn, Values: []ast.Expr{target}}
	return &ast.FuncDecl{
		Name: ident("check_" + g.checkName(name)), Type: &ast.FuncType{TypeParams: g.typeParams(vars), Params: &ast.FieldList{}},
		Body: block(&ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{spec}}}),
	}
}

// checkName keeps check names unique when one native implements a contract
// for several receivers.
func (g *gen) checkName(name string) string {
	if g.checks == nil {
		g.checks = map[string]int{}
	}
	g.checks[name]++
	if n := g.checks[name]; n > 1 {
		return name + "_" + itoa(n)
	}
	return name
}

func unnamed(fields []*ast.Field) []*ast.Field {
	out := make([]*ast.Field, len(fields))
	for i, f := range fields {
		out[i] = &ast.Field{Type: f.Type}
	}
	return out
}

func varArgs(vars []*checker.Type) []ast.Expr {
	var out []ast.Expr
	for _, v := range vars {
		out = append(out, ident(v.Name))
	}
	return out
}

func (g *gen) standardFunctionCheck(s *checker.Symbol) ast.Decl {
	name := nativeName(s.Native)
	caps := checker.BoundCapabilities(s.Variables)
	params := []*ast.Field{field("ctx", pointerTo(ident("Execution")))}
	params = append(params, g.capabilityFields(caps)...)
	for _, p := range s.Type.Params {
		params = append(params, field(p.Name, g.goType(p.Type)))
	}
	return g.functionCheck(name, s.Variables, params, g.goType(s.Type.Result), generic(ident(name), varArgs(s.Variables)...))
}

func (g *gen) standardOperationCheck(op checker.NativeOperation) ast.Decl {
	receiver := op.Receiver
	base := receiver.Name
	if receiver.Kind == "primitive" {
		base = receiver.ID
	}
	name := base + "_" + camel(op.Name)
	var vars []*checker.Type
	if receiver.Def != nil {
		vars = append(vars, receiver.Def.Variables...)
	}
	vars = append(vars, op.Variables...)
	caps := checker.OperationCapabilities(receiver, op.Requirements, op.Variables)
	params := []*ast.Field{field("ctx", pointerTo(ident("Execution")))}
	params = append(params, g.capabilityFields(caps)...)
	params = append(params, field("self", g.receiverType(receiver)))
	for _, p := range op.Type.Params {
		params = append(params, field(p.Name, g.goType(p.Type)))
	}
	return g.functionCheck(name, vars, params, g.goType(op.Type.Result), generic(ident(name), varArgs(vars)...))
}

// receiverType is the Go type of a receiver written in its own variables.
func (g *gen) receiverType(t *checker.Type) ast.Expr {
	if t.Kind == "primitive" {
		return g.goType(t)
	}
	var args []*checker.Type
	for _, v := range t.Def.Variables {
		args = append(args, v)
	}
	instance := *t
	instance.Args = args
	return g.goType(&instance)
}

func (g *gen) standardImplementationCheck(m *checker.Method) ast.Decl {
	name := implName(m, m.Receiver)
	params := []*ast.Field{field("ctx", pointerTo(ident("Execution"))), field("self", g.goType(m.Receiver))}
	for _, p := range m.Type.Params {
		params = append(params, field(p.Name, g.goType(p.Type)))
	}
	return g.functionCheck(name, m.Variables, params, g.goType(m.Type.Result), generic(ident(name), varArgs(m.Variables)...))
}

