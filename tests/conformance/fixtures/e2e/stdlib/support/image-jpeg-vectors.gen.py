#!/usr/bin/env python3
"""Regenerates image-jpeg-vectors.ms: JPEG files written by Pillow/libjpeg (baseline, progressive,
every common subsampling, gray, CMYK) with libjpeg's own decoded pixels as the expected output.
Run: python3 image-jpeg-vectors.gen.py > image-jpeg-vectors.ms"""
import io, math
from PIL import Image

def scene(w, h):
    im = Image.new("RGB", (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = (int(255 * x / max(1, w - 1)), int(255 * y / max(1, h - 1)),
                        int(127 + 120 * math.sin((x + y) / 5.0)))
    return im

cases = []
def add(name, im, tol, **save):
    b = io.BytesIO(); im.save(b, "JPEG", **save)
    data = b.getvalue()
    dec = Image.open(io.BytesIO(data))
    mode = "L" if dec.mode == "L" else "RGB"
    dec = dec.convert(mode)
    cases.append((name, dec.width, dec.height, len(mode) if mode != "L" else 1, tol, data, list(dec.tobytes())))

base = scene(30, 21)
add("gray", base.convert("L"), 2, quality=90)
add("rgb444", base, 2, quality=92, subsampling=0)
add("rgb422", base, 2, quality=92, subsampling=1)
add("rgb420", base, 2, quality=92, subsampling=2)
add("progressive444", base, 2, quality=90, subsampling=0, progressive=True)
add("progressive420", base, 2, quality=90, subsampling=2, progressive=True)
add("gray-progressive", base.convert("L"), 2, quality=85, progressive=True)
add("optimized", base, 2, quality=75, optimize=True)
add("tiny-1x1", Image.new("RGB", (1, 1), (200, 30, 90)), 2, quality=95)
add("odd-17x9", scene(17, 9), 2, quality=88, subsampling=2)
add("cmyk", scene(16, 16).convert("CMYK"), 2, quality=95)
add("low-quality", base, 2, quality=20, subsampling=0)

print("// Generated by image-jpeg-vectors.gen.py; do not edit.")
print("")
print("export type JpegVector:")
print("    name: String")
print("    width: Int")
print("    height: Int")
print("    channels: Int")
print("    tolerance: Int")
print("    jpeg: String")
print("    pixels: List[Int]")
print("")
print("export fn jpeg_vectors() List[JpegVector]:")
print("    return [")
for i, (name, w, h, ch, tol, data, px) in enumerate(cases):
    print('        JpegVector("%s", %d, %d, %d, %d, "%s", [%s])%s' % (name, w, h, ch, tol, data.hex(), ", ".join(map(str, px)), "," if i < len(cases)-1 else ""))
print("    ]")
