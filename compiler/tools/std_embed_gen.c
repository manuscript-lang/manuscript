#define _POSIX_C_SOURCE 200809L
/* std_embed_gen STDLIB_DIR OUT: writes the C source that embeds the standard library, the files
 * chosen as crates/ms-check/build.rs chooses them, in file-name order. compiler/src/std_embed.c
 * includes the output. */
#include <stdio.h>
#include <string.h>

#include "std_files.h"

/* One source line of the file as a string literal: escapes keep it valid in any C compiler. */
static void put_literal_line(FILE *out, const char *text, size_t length) {
    fputs("    \"", out);
    for (size_t i = 0; i < length; i++) {
        unsigned char c = (unsigned char)text[i];
        if (c == '\\' || c == '"' || c == '?') {
            fprintf(out, "\\%c", c);
        } else if (c >= 0x20 && c < 0x7f) {
            fputc(c, out);
        } else {
            fprintf(out, "\\%03o", c);
        }
    }
    fputs("\"\n", out);
}

static void put_file(FILE *out, const MsStdFile *file, uint32_t index) {
    fprintf(out, "static const char std_text_%u[] =\n", index);
    size_t start = 0;
    for (size_t i = 0; i < file->len; i++) {
        if (file->text[i] == '\n') {
            put_literal_line(out, file->text + start, i + 1 - start);
            start = i + 1;
        }
    }
    put_literal_line(out, file->text + start, file->len - start);
    fputs(";\n", out);
}

int main(int argc, char **argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: std_embed_gen STDLIB_DIR OUT\n");
        return 2;
    }
    StdFiles files = {0};
    if (!read_std_files(&files, argv[1])) {
        free_std_files(&files);
        return 1;
    }
    qsort(files.items, files.count, sizeof *files.items, ms_std_file_by_name);
    FILE *out = fopen(argv[2], "wb");
    if (out == NULL) {
        fprintf(stderr, "cannot write %s\n", argv[2]);
        free_std_files(&files);
        return 1;
    }
    fputs("/* Generated by compiler/tools/std_embed_gen.c from stdlib/. */\n", out);
    for (uint32_t i = 0; i < files.count; i++) {
        put_file(out, &files.items[i], i);
    }
    fputs("static const MsStdFile std_embedded[] = {\n", out);
    for (uint32_t i = 0; i < files.count; i++) {
        fprintf(out, "    {\"%s\", std_text_%u, sizeof std_text_%u - 1},\n", files.items[i].name, i, i);
    }
    fprintf(out, "};\nstatic const uint32_t std_embedded_count = %u;\n", files.count);
    bool ok = fclose(out) == 0;
    free_std_files(&files);
    return ok ? 0 : 1;
}
