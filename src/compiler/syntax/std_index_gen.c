/* Build-time tool: lists where the function bodies of the bundled standard library sit, for lazy parsing.
 *
 *   std_index_gen <stdlib dir> <list file> <output .c>
 *
 * The list file has one `name<TAB>path` line per bundled file, in the order of the generated embedding. Each file is parsed
 * with the real parser, which reports every body it could skip. The tool then checks the index: the file parsed with
 * those bodies left out, then each body parsed apart, must give the very tree of the whole parse (same ids, kinds and
 * positions), so a stale or wrong index fails the build and cannot reach a user. */
#include <stdio.h>

#include "base/arena.h"
#include "base/file.h"
#include "base/intern.h"
#include "base/strbuild.h"
#include "compiler/syntax/parse.h"
#include "compiler/syntax/walk.h"

typedef struct Digest {
  uint64_t hash;
  size_t nodes;
} Digest;

static void mix(Digest *digest, uint64_t value) {
  digest->hash = (digest->hash ^ value) * 1099511628211ULL;
}

static void mix_pos(Digest *digest, MsPos pos) {
  mix(digest, pos.offset);
  mix(digest, pos.line);
  mix(digest, pos.column);
}

static void digest_stmt(void *ctx, const MsStmt *stmt) {
  Digest *digest = ctx;
  mix(digest, stmt->id);
  mix(digest, (uint64_t)stmt->kind);
  mix_pos(digest, stmt->pos);
  digest->nodes++;
}

static void digest_expr(void *ctx, const MsExpr *expr) {
  Digest *digest = ctx;
  mix(digest, expr->id);
  mix(digest, (uint64_t)expr->kind);
  mix_pos(digest, expr->pos);
  digest->nodes++;
}

/* Parses the body of `func` if it was left out. False when it does not parse. */
static bool restore_body(MsArena *arena, MsNames *names, MsSpan source, MsFunc *func, MsDiag *diag) {
  if (func->lazy.end == 0) {
    return true;
  }
  if (!ms_parse_body(arena, names, source, func->lazy, &func->body, diag)) {
    return false;
  }
  func->deferred = false;
  func->lazy = (MsBodyRange){0};
  return true;
}

/* Parses the bodies of `module` that were left out, in place. False when one does not parse. */
static bool restore_bodies(MsArena *arena, MsNames *names, MsSpan source, MsModule *module, MsDiag *diag) {
  for (uint32_t index = 0; index < module->ndecls; index++) {
    MsDecl *decl = (MsDecl *)(void *)module->decls[index];
    if (decl->kind == MS_D_FN && !restore_body(arena, names, source, &decl->u.fn, diag)) {
      return false;
    }
    for (uint32_t at = 0; decl->kind == MS_D_IMPL && at < decl->u.impl.methods.len; at++) {
      if (!restore_body(arena, names, source, &decl->u.impl.methods.ptr[at]->func, diag)) {
        return false;
      }
    }
  }
  return true;
}

static Digest digest_module(const MsModule *module) {
  Digest digest = {14695981039346656037ULL, 0};
  const MsVisitor visitor = {.ctx = &digest, .stmt = digest_stmt, .expr = digest_expr};
  mix(&digest, module->node_count);
  mix(&digest, module->ndecls);
  for (uint32_t index = 0; index < module->ndecls; index++) {
    mix(&digest, module->decls[index]->id);
    mix_pos(&digest, module->decls[index]->pos);
    ms_walk_decl(&visitor, module->decls[index]);
  }
  return digest;
}

/* Checks one file; fills `ranges`. Returns false after reporting the problem. */
static bool index_file(MsArena *arena, MsSpan name, MsSpan source, MsBodyRange **ranges, size_t *count) {
  MsNames names;
  ms_names_init(&names);
  MsDiag diag = {0};
  MsModule whole = {0};
  MsModule lazy = {0};
  bool ok = ms_parse_bodies(arena, &names, source, NULL, 0, ranges, count, &whole, &diag);
  ok = ok && ms_parse_bodies(arena, &names, source, *ranges, *count, NULL, NULL, &lazy, &diag);
  ok = ok && lazy.node_count == whole.node_count && restore_bodies(arena, &names, source, &lazy, &diag);
  if (!ok) {
    (void)fprintf(stderr, "std_index_gen: %.*s: %s at line %u: %.*s\n", (int)name.len, name.ptr,
                  lazy.node_count == whole.node_count ? "does not parse" : "node count differs", diag.pos.line,
                  (int)diag.message.len, diag.message.ptr);
    return false;
  }
  const Digest a = digest_module(&whole);
  const Digest b = digest_module(&lazy);
  if (a.hash != b.hash || a.nodes != b.nodes) {
    (void)fprintf(stderr, "std_index_gen: %.*s: the lazily parsed tree differs from the whole parse\n", (int)name.len,
                  name.ptr);
    return false;
  }
  ms_names_free(&names);
  return true;
}

int main(int argc, char **argv) {
  if (argc != 4) {
    (void)fprintf(stderr, "usage: std_index_gen <stdlib dir> <list file> <output.c>\n");
    return 2;
  }
  MsArena arena = ms_arena_new();
  MsBytes list = {0};
  if (!ms_file_read(ms_span_of_text(argv[2]), &list)) {
    (void)fprintf(stderr, "std_index_gen: cannot read %s\n", argv[2]);
    return 1;
  }
  MsStrBuild out = ms_strbuild_new();
  ms_strbuild_append_text(&out, "/* Generated by std_index_gen from src/stdlib/. Do not edit. */\n#include \"compiler/project/project.h\"\n\n");
  size_t index = 0;
  const uint8_t *cursor = list.ptr;
  const uint8_t *end = list.ptr + list.len;
  while (cursor < end) {
    const uint8_t *line_end = cursor;
    while (line_end < end && *line_end != '\n') {
      line_end++;
    }
    const uint8_t *tab = cursor;
    const uint8_t *text_end = line_end > cursor && line_end[-1] == '\r' ? line_end - 1 : line_end; /* a CRLF list */
    while (tab < line_end && *tab != '\t') {
      tab++;
    }
    const MsSpan name = {cursor, (size_t)(tab - cursor)};
    MsStrBuild path = ms_strbuild_new();
    ms_strbuild_append_text(&path, argv[1]);
    ms_strbuild_append_text(&path, "/");
    ms_strbuild_append(&path, (MsSpan){tab + 1, (size_t)(text_end - tab - 1)});
    MsBytes source = {0};
    if (!ms_file_read(ms_strbuild_span(&path), &source)) {
      (void)fprintf(stderr, "std_index_gen: cannot read '%.*s' (%zu bytes)\n", (int)ms_strbuild_length(&path),
                    (const char *)ms_strbuild_span(&path).ptr, ms_strbuild_length(&path));
      return 1;
    }
    MsBodyRange *ranges = NULL;
    size_t count = 0;
    if (!index_file(&arena, name, (MsSpan){source.ptr, source.len}, &ranges, &count)) {
      return 1;
    }
    ms_strbuild_printf(&out, "const MsBodyRange std_bodies_%zu[] = {\n", index);
    for (size_t at = 0; at < count; at++) {
      ms_strbuild_printf(&out, "    {%u, %u, %u, %u, %u, %s},\n", ranges[at].start, ranges[at].end, ranges[at].line,
                          ranges[at].first_id, ranges[at].end_id, ranges[at].arrow ? "true" : "false");
    }
    ms_strbuild_printf(&out, "    {0, 0, 0, 0, 0, false}};\nconst size_t std_nbodies_%zu = %zu;\n\n", index, count);
    ms_strbuild_free(&path);
    index++;
    cursor = line_end + 1;
  }
  if (!ms_file_write(ms_span_of_text(argv[3]), ms_strbuild_span(&out))) {
    (void)fprintf(stderr, "std_index_gen: cannot write %s\n", argv[3]);
    return 1;
  }
  return 0;
}
