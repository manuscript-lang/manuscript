//! Foreign content tables and predicates, ported from `foreign.go`.
use crate::parse::{Node, NodeType};
use crate::token::Attribute;
use alloc::string::String;

pub fn adjust_attribute_names(aa: &mut [Attribute], map: fn(&str) -> Option<&'static str>) {
    for a in aa {
        if let Some(n) = map(&a.key) {
            a.key = String::from(n);
        }
    }
}

pub fn adjust_foreign_attributes(aa: &mut [Attribute]) {
    for a in aa {
        if !a.key.starts_with('x') {
            continue;
        }
        if matches!(
            a.key.as_str(),
            "xlink:actuate"
                | "xlink:arcrole"
                | "xlink:href"
                | "xlink:role"
                | "xlink:show"
                | "xlink:title"
                | "xlink:type"
                | "xml:base"
                | "xml:lang"
                | "xml:space"
                | "xmlns:xlink"
        ) && let Some(j) = a.key.find(':')
        {
            a.namespace = String::from(&a.key[..j]);
            a.key = String::from(&a.key[j + 1..]);
        }
    }
}

pub fn html_integration_point(n: &Node) -> bool {
    if n.ty != NodeType::Element {
        return false;
    }
    match n.namespace.as_str() {
        "math" => {
            n.data == "annotation-xml"
                && n.attr.iter().any(|a| {
                    a.key == "encoding"
                        && (a.val.eq_ignore_ascii_case("text/html")
                            || a.val.eq_ignore_ascii_case("application/xhtml+xml"))
                })
        }
        "svg" => matches!(n.data.as_str(), "desc" | "foreignObject" | "title"),
        _ => false,
    }
}

pub fn math_ml_text_integration_point(n: &Node) -> bool {
    n.namespace == "math" && matches!(n.data.as_str(), "mi" | "mo" | "mn" | "ms" | "mtext")
}

