//! The untyped Manuscript syntax tree.
//!
//! Position and shape conventions:
//!
//! * `pos` fields carry exact positions, including the unusual ones: a
//!   binary expression sits at its **operator**, a member access at the
//!   **member name**, a call/index/apply at its **callee's start**, a method
//!   declaration at its **name**, a top-level declaration at its keyword.
//! * Pipes are desugared by the parser: `x | f(a: 1)` is the
//!   call `f(x, a: 1)` (first argument at `x`'s position), `x | .m()` is
//!   `x.m()`, and `x | try` / `x | try step` wrap in [`UnaryOp::Try`]. Use the
//!   source text if the written form matters (the formatter does).
//! * Compound assignment `a.b += 1` is [`StmtKind::Assign`] with
//!   `compound = Some(op)` and `value` = `a.b + 1` (a fresh clone of the target
//!   chain on the left, positioned at the target, binary positioned at the
//!   operator).
//! * `let (a = 1, ...)` groups are expanded into one node each with `group`
//!   set to the keyword position.
//! * A module-level `let` is [`DeclKind::Const`]; it is held as a nullary
//!   function whose body returns the initializer (see [`ConstDecl`]).
//! * A statement-position expression in an inline function/arm body is parsed
//!   as [`StmtKind::Return`].
//!
//! # Node ids
//!
//! Every node that can carry a checker fact has a [`NodeId`], unique within its
//! [`Module`] and dense in `0..module.node_count`. Later passes keep facts in
//! `Vec`s indexed by id (side tables) rather than on the nodes. Clones made by
//! the parser (compound-assignment targets) have their own ids.
//!
//! Synthetic declarations the checker builds for `impl Type:`  are created by the checker, never by the parser;
//! [`Decl::synthetic`] exists so they can be represented.

use crate::pos::{Pos, Span};
use crate::symbol::Symbol;
use std::sync::Arc;

/// Identifies a node within one [`Module`]; dense, starting at 0.
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct NodeId(pub u32);

impl NodeId {
    /// The id as a table index.
    pub fn index(self) -> usize {
        self.0 as usize
    }
}

/// A parsed source file.
#[derive(Debug, Default)]
pub struct Module {
    /// File name as given to the parser.
    pub file: Arc<str>,
    /// Original source text (including any CRLF line endings).
    pub source: Arc<str>,
    /// Import bindings; a named import list expands to one entry per name.
    pub imports: Vec<Import>,
    /// Top-level declarations in source order (grouped constants expanded).
    pub decls: Vec<Decl>,
    /// Names of declarations editor recovery dropped because they did not
    /// parse; uses of them are not reported as unknown.
    pub omitted: Vec<String>,
    /// Source ranges of declarations whose invalid statements editor recovery
    /// blanked; checking diagnostics inside them are suppressed because their
    /// syntax error is already reported.
    pub recovered: Vec<Span>,
    /// Number of [`NodeId`]s allocated; ids are `0..node_count`.
    pub node_count: u32,
}

/// One imported symbol binding: `import { A, B } from "path"` yields two.
#[derive(Debug, Clone)]
pub struct Import {
    /// Node id.
    pub id: NodeId,
    /// Position of the `import` keyword (shared by the names of one list).
    pub pos: Pos,
    /// Position of the imported name.
    pub name_pos: Pos,
    /// Imported name.
    pub name: Symbol,
    /// Import path text (no interpolation allowed).
    pub path: Box<str>,
}

/// A top-level declaration.
#[derive(Debug, Clone)]
pub struct Decl {
    /// Node id.
    pub id: NodeId,
    /// Keyword position (`fn`, `type`, `test`, ...); for a grouped constant,
    /// the position of the entry's name. See [`ConstDecl::group`].
    pub pos: Pos,
    /// Written with `export`.
    pub export: bool,
    /// Generated by the checker for `impl Type:` (never set by the parser).
    pub synthetic: bool,
    /// What the declaration is.
    pub kind: DeclKind,
}

/// Declaration variants.
#[derive(Debug, Clone)]
pub enum DeclKind {
    /// `fn name[T](params) Result:` with a body.
    Fn(Func),
    /// Module-level `let name [: Type] = value`.
    Const(ConstDecl),
    /// `type Name:` with `field: Type [= default]` lines.
    Record(RecordDecl),
    /// `type Name:` with `case` lines.
    Alternative(AlternativeDecl),
    /// `interface Name:` with `fn` signatures.
    Interface(InterfaceDecl),
    /// `impl [Contract for] Type:` with methods.
    Impl(ImplDecl),
    /// `test "name":` block.
    Test(TestDecl),
}

/// A function: top-level `fn`, or the shared shape of methods.
#[derive(Debug, Clone)]
pub struct Func {
    /// Function name.
    pub name: Symbol,
    /// Generic parameters.
    pub type_params: Vec<TypeParam>,
    /// Value parameters (defaults allowed).
    pub params: Vec<Param>,
    /// Declared result type (mandatory in source).
    pub result: TypeRef,
    /// Written `ref T`: the result lends part of a borrowed parameter or receiver.
    pub result_ref: bool,
    /// Body statements; may be empty for an empty declaration suite.
    pub body: Vec<Stmt>,
    /// `extern fn`: a native symbol with no body, named after the function.
    pub external: bool,
}

/// A module-level constant.
///
/// Stored as a function without parameters whose body is
/// `return value`, with `Result` the annotation or a placeholder at the
/// initializer. Every use evaluates the initializer. The synthetic return
/// statement is positioned at the **first token** of the initializer
/// ([`ConstDecl::init_pos`]); `value.pos` can differ (a binary expression is at
/// its operator).
#[derive(Debug, Clone)]
pub struct ConstDecl {
    /// Constant name.
    pub name: Symbol,
    /// Annotation, if written. When absent, the checker infers the type from `value`.
    pub ty: Option<TypeRef>,
    /// Initializer.
    pub value: Expr,
    /// Position of the initializer's first token.
    pub init_pos: Pos,
    /// Position of the `let` keyword when written inside `let ( ... )`.
    pub group: Option<Pos>,
}

/// `type Name[T]:` with fields.
#[derive(Debug, Clone)]
pub struct RecordDecl {
    /// Type name.
    pub name: Symbol,
    /// Generic parameters.
    pub type_params: Vec<TypeParam>,
    /// Fields in declaration order; `ty` is always present.
    pub fields: Vec<Param>,
}

/// `type Name[T]:` with `case` lines.
#[derive(Debug, Clone)]
pub struct AlternativeDecl {
    /// Type name.
    pub name: Symbol,
    /// Generic parameters.
    pub type_params: Vec<TypeParam>,
    /// Cases in declaration order.
    pub cases: Vec<Case>,
}

/// `interface Name[T]:` with operation signatures.
#[derive(Debug, Clone)]
pub struct InterfaceDecl {
    /// Interface name.
    pub name: Symbol,
    /// Generic parameters.
    pub type_params: Vec<TypeParam>,
    /// Operation signatures; bodies are empty.
    pub methods: Vec<Method>,
}

/// `impl Contract for Type:` or `impl Type:`.
#[derive(Debug, Clone)]
pub struct ImplDecl {
    /// The contract for `impl Contract for Type`; `None` for `impl Type`.
    pub contract: Option<TypeRef>,
    /// The implementing type.
    pub receiver: TypeRef,
    /// Methods, each with a body.
    pub methods: Vec<Method>,
}

impl ImplDecl {
    /// Display name: `"Contract for Type"` or `"Type"`.
    pub fn display_name(&self, synthetic: bool) -> String {
        match (&self.contract, synthetic) {
            (Some(c), false) => format!("{} for {}", c.name(), self.receiver.name()),
            _ => self.receiver.name().to_string(),
        }
    }
}

/// `test "name":` block; it implicitly returns `Unit`.
#[derive(Debug, Clone)]
pub struct TestDecl {
    /// Test name (plain text, no interpolation).
    pub name: Box<str>,
    /// Body statements.
    pub body: Vec<Stmt>,
}

/// A method in an `impl` or an operation signature in an `interface`.
#[derive(Debug, Clone)]
pub struct Method {
    /// Node id.
    pub id: NodeId,
    /// Position of the method **name**.
    pub pos: Pos,
    /// Name, generics, parameters, result and body.
    pub func: Func,
    /// Declared `var fn`: the method may change its receiver.
    pub mutating: bool,
}

/// One `case Name[(fields)]` of an alternative type.
#[derive(Debug, Clone)]
pub struct Case {
    /// Node id.
    pub id: NodeId,
    /// Position of the case name.
    pub pos: Pos,
    /// Case name.
    pub name: Symbol,
    /// Payload fields (never empty when written; no defaults).
    pub fields: Vec<Param>,
}

/// A parameter, record field, or case payload field.
#[derive(Debug, Clone)]
pub struct Param {
    /// Node id.
    pub id: NodeId,
    /// Position of the name.
    pub pos: Pos,
    /// Name.
    pub name: Symbol,
    /// Declared type; `None` only for lambda parameters with inferred types.
    pub ty: Option<TypeRef>,
    /// Default value, where the grammar allows one.
    pub default: Option<Expr>,
    /// Declared `var name: Type`: the callee may change the argument.
    pub mutable: bool,
}

/// A generic parameter `T: Bound & Other = Default`.
#[derive(Debug, Clone)]
pub struct TypeParam {
    /// Node id.
    pub id: NodeId,
    /// Position of the name.
    pub pos: Pos,
    /// Name.
    pub name: Symbol,
    /// Required contracts.
    pub bounds: Vec<TypeRef>,
    /// Type argument used when none is supplied or inferred.
    pub default: Option<TypeRef>,
}

/// A written type.
#[derive(Debug, Clone)]
pub struct TypeRef {
    /// Node id.
    pub id: NodeId,
    /// Start position.
    pub pos: Pos,
    /// Variant.
    pub kind: TypeKind,
}

/// Type variants.
#[derive(Debug, Clone)]
pub enum TypeKind {
    /// `Name`, `module.Name`, `Name[Args]`. `name` keeps the dotted spelling
    /// (`"a.B"`).
    Named {
        /// Possibly dotted name.
        name: Symbol,
        /// Type arguments.
        args: Vec<TypeRef>,
    },
    /// `fn(name: Type) Result`.
    Fn {
        /// Parameters (names and types required, no defaults).
        params: Vec<Param>,
        /// Result type.
        result: Box<TypeRef>,
    },
}

impl TypeRef {
    /// The type name; `"fn"` for function types.
    pub fn name(&self) -> &str {
        match &self.kind {
            TypeKind::Named { name, .. } => name.as_str(),
            TypeKind::Fn { .. } => "fn",
        }
    }
}

/// An expression.
#[derive(Debug, Clone)]
pub struct Expr {
    /// Node id.
    pub id: NodeId,
    /// Position (see the module docs for node-specific anchors).
    pub pos: Pos,
    /// Variant.
    pub kind: ExprKind,
}

/// Expression variants .
#[derive(Debug, Clone)]
pub enum ExprKind {
    /// Number literal; the symbol is the exact spelling (`1_000` is not valid;
    /// `1.5d`, `2e3` are).
    Number(Symbol),
    /// `true` / `false`.
    Bool(bool),
    /// `unit`.
    Unit,
    /// Text literal; at least one part (an empty literal is one empty part).
    Text(Vec<TextPart>),
    /// A name, including `self`, `fixture` and the arm path `_`.
    Name(Symbol),
    /// `left.name`; positioned at the member name.
    Member {
        /// Receiver.
        left: Box<Expr>,
        /// Member name.
        name: Symbol,
    },
    /// `left[T, ...]`: the bracket read as type arguments. When exactly one
    /// argument is written and it can also be a value (not a `fn` type),
    /// `value` holds the value interpretation , so `xs[i]` is
    /// retained both ways until name resolution identifies the receiver.
    Apply {
        /// Receiver.
        left: Box<Expr>,
        /// Type interpretation of the bracket contents.
        types: Vec<TypeRef>,
        /// Value interpretation of a single type argument.
        value: Option<Box<Expr>>,
    },
    /// `left[index]` where the bracket cannot be read as types.
    Index {
        /// Receiver.
        left: Box<Expr>,
        /// Index expression.
        index: Box<Expr>,
    },
    /// `[a, b]`.
    List(Vec<Expr>),
    /// `{k: v, ...}`.
    Map(Vec<MapEntry>),
    /// Prefix operator; positioned at the operator.
    Unary {
        /// Operator.
        op: UnaryOp,
        /// Operand.
        operand: Box<Expr>,
    },
    /// Infix operator; positioned at the **operator**.
    Binary {
        /// Operator.
        op: BinaryOp,
        /// Left operand.
        left: Box<Expr>,
        /// Right operand.
        right: Box<Expr>,
    },
    /// `fn(params) [Result]: body`.
    Lambda(Lambda),
    /// `callee(args)`; positioned at the callee's start.
    Call {
        /// Called expression.
        callee: Box<Expr>,
        /// Arguments in order (a piped value is first, at the piped expression's position).
        args: Vec<Argument>,
    },
    /// `match scrutinee:` with arms.
    Match {
        /// Matched value.
        scrutinee: Box<Expr>,
        /// Arms in source order (at least one).
        arms: Vec<Arm>,
    },
}

impl Expr {
    /// A written `match`, not the Bool match an `if` expression stands for.
    pub fn is_written_match(&self) -> bool {
        matches!(&self.kind, ExprKind::Match { arms, .. } if !arms.first().is_some_and(|a| a.from_if))
    }
}

/// A `key: value` map literal entry.
#[derive(Debug, Clone)]
pub struct MapEntry {
    /// Key expression.
    pub key: Expr,
    /// Value expression.
    pub value: Expr,
}

/// A function expression.
#[derive(Debug, Clone)]
pub struct Lambda {
    /// Parameters; types optional.
    pub params: Vec<Param>,
    /// Written result type, if any.
    pub result: Option<Box<TypeRef>>,
    /// Body; an inline `fn(x) T: expr` body is a single [`StmtKind::Return`].
    pub body: Vec<Stmt>,
}

/// A call argument.
#[derive(Debug, Clone)]
pub struct Argument {
    /// Start of the argument (its label, or its value).
    pub pos: Pos,
    /// Label (`name: value`), if written.
    pub name: Option<Symbol>,
    /// Value.
    pub value: Expr,
    /// Written `var value`: the callee may change the place passed.
    pub mutable: bool,
}

/// A part of a text literal.
#[derive(Debug, Clone)]
pub enum TextPart {
    /// Literal text with escapes already decoded.
    Lit(Box<str>),
    /// `{expression}`; positions point into the original source.
    Interp(Expr),
}

/// Prefix operators.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum UnaryOp {
    /// `not`
    Not,
    /// unary `-`
    Neg,
    /// unary `+`
    Plus,
    /// `try`
    Try,
}

impl UnaryOp {
    /// Source spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            UnaryOp::Not => "not",
            UnaryOp::Neg => "-",
            UnaryOp::Plus => "+",
            UnaryOp::Try => "try",
        }
    }
}

/// Infix operators.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum BinaryOp {
    /// `or`
    Or,
    /// `and`
    And,
    /// `==`
    Eq,
    /// `!=`
    Ne,
    /// `<`
    Lt,
    /// `>`
    Gt,
    /// `<=`
    Le,
    /// `>=`
    Ge,
    /// `+`
    Add,
    /// `-`
    Sub,
    /// `*`
    Mul,
    /// `/`
    Div,
    /// `%`
    Rem,
}

impl BinaryOp {
    /// Source spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            BinaryOp::Or => "or",
            BinaryOp::And => "and",
            BinaryOp::Eq => "==",
            BinaryOp::Ne => "!=",
            BinaryOp::Lt => "<",
            BinaryOp::Gt => ">",
            BinaryOp::Le => "<=",
            BinaryOp::Ge => ">=",
            BinaryOp::Add => "+",
            BinaryOp::Sub => "-",
            BinaryOp::Mul => "*",
            BinaryOp::Div => "/",
            BinaryOp::Rem => "%",
        }
    }

    /// Binding power used by the parser (higher binds tighter).
    pub fn precedence(self) -> u8 {
        match self {
            BinaryOp::Or => 1,
            BinaryOp::And => 2,
            BinaryOp::Eq
            | BinaryOp::Ne
            | BinaryOp::Lt
            | BinaryOp::Gt
            | BinaryOp::Le
            | BinaryOp::Ge => 4,
            BinaryOp::Add | BinaryOp::Sub => 5,
            BinaryOp::Mul | BinaryOp::Div | BinaryOp::Rem => 6,
        }
    }
}

/// One `match` arm.
#[derive(Debug, Clone)]
pub struct Arm {
    /// Node id.
    pub id: NodeId,
    /// Start of the arm.
    pub pos: Pos,
    /// Case path: a [`ExprKind::Name`] (`_` for the wildcard), a dotted
    /// [`ExprKind::Member`] chain, optionally with an [`ExprKind::Apply`].
    pub path: Expr,
    /// Payload bindings `(a, _)`, including `_` placeholders.
    pub bindings: Vec<ArmBinding>,
    /// Statements before the arm's value.
    pub body: Vec<Stmt>,
    /// The arm's final expression; `None` yields `Unit`.
    pub value: Option<Expr>,
    /// The arm is a branch of an `if` expression written `if c: a else: b`.
    pub from_if: bool,
}

/// A payload binding in a match arm.
#[derive(Debug, Clone)]
pub struct ArmBinding {
    /// Name or `_`.
    pub name: Symbol,
    /// Original position.
    pub pos: Pos,
}

/// A binding pattern.
#[derive(Debug, Clone)]
pub struct Pattern {
    /// Node id.
    pub id: NodeId,
    /// Start position.
    pub pos: Pos,
    /// Variant.
    pub kind: PatternKind,
}

/// Pattern variants.
#[derive(Debug, Clone)]
pub enum PatternKind {
    /// A plain name.
    Name(Symbol),
    /// `[a, b]`.
    List(Vec<Pattern>),
    /// `{x, y: [a, b]}`.
    Record(Vec<PatternField>),
}

/// A field of a record pattern. `{x}` is the field `x` bound to the pattern
/// name `x` (positioned at the field).
#[derive(Debug, Clone)]
pub struct PatternField {
    /// Position of the field name.
    pub pos: Pos,
    /// Field name.
    pub name: Symbol,
    /// Pattern bound to the field.
    pub pattern: Pattern,
}

/// A statement.
#[derive(Debug, Clone)]
pub struct Stmt {
    /// Node id.
    pub id: NodeId,
    /// Start position (first token of the statement; for an assignment, of its target).
    pub pos: Pos,
    /// Variant.
    pub kind: StmtKind,
}

/// The target of an assignment.
#[derive(Debug, Clone)]
pub enum AssignTarget {
    /// A local binding name.
    Name(Symbol),
    /// A record field (`a.b`); always an [`ExprKind::Member`].
    Member(Expr),
}

/// Statement variants.
#[derive(Debug, Clone)]
pub enum StmtKind {
    /// `let`/`var` binding: `pattern [: Type] = value`.
    Bind {
        /// `var` rather than `let`.
        mutable: bool,
        /// Written `let ref` / `var ref`: borrows the place instead of copying it.
        by_ref: bool,
        /// Bound pattern.
        pattern: Pattern,
        /// Annotation (only for a plain name pattern).
        ty: Option<TypeRef>,
        /// Initializer.
        value: Expr,
        /// Keyword position when written in a `let ( ... )` group.
        group: Option<Pos>,
    },
    /// `target = value` or `target op= value`.
    Assign {
        /// Assigned place.
        target: AssignTarget,
        /// Operator of a compound assignment; `value` is then the equivalent
        /// binary expression over the target.
        compound: Option<BinaryOp>,
        /// Assigned value.
        value: Expr,
    },
    /// An expression statement (call, `try` call or `match`).
    Call(Expr),
    /// `return [value]`; also an inline body's expression.
    Return(Option<Expr>),
    /// `break`
    Break,
    /// `continue`
    Continue,
    /// `if [let|var name =] cond:` with optional `else`.
    If {
        /// `if let name = value` binding pattern (always a plain name).
        binding: Option<Pattern>,
        /// `if var name = value`: the binding is an exclusive borrow of the payload.
        mutable: bool,
        /// Condition, or the Optional value of `if let`.
        cond: Expr,
        /// Then-branch.
        body: Vec<Stmt>,
        /// Else-branch; `else if` is a single [`StmtKind::If`].
        else_body: Vec<Stmt>,
    },
    /// `while cond:`
    While {
        /// Condition.
        cond: Expr,
        /// Body.
        body: Vec<Stmt>,
    },
    /// `for name in iter:`
    For {
        /// Loop variable.
        name: Symbol,
        /// Iterated value.
        iter: Expr,
        /// Body.
        body: Vec<Stmt>,
    },
    /// `with name = resource:`
    With {
        /// Bound name.
        name: Symbol,
        /// Resource expression.
        value: Expr,
        /// Body.
        body: Vec<Stmt>,
    },
}

impl Module {
    /// Allocates the next node id (used by the parser and by passes that
    /// synthesise nodes).
    pub fn fresh_id(&mut self) -> NodeId {
        let id = NodeId(self.node_count);
        self.node_count += 1;
        id
    }
}
