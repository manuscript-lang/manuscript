// Message text of every standard error case; keep in sync with `stdlib/*.ms`.

use crate::iface::Message::{self, Cause, Payload, Text};

/// The `message()` text of each case of a standard error type.
pub(crate) fn table(name: &str) -> Option<&'static [(&'static str, Message)]> {
    Some(match name {
        "ArchiveError" => &[
            ("InvalidInput", Text("archive: invalid input")),
            ("InvalidData", Text("archive: invalid data")),
            ("LimitExceeded", Text("archive: limit exceeded")),
            ("Unsupported", Text("archive: operation not supported")),
            ("Failed", Payload),
        ],
        "BigIntError" => &[
            ("InvalidInput", Text("big integer: invalid input")),
            ("InvalidData", Text("big integer: invalid data")),
            ("LimitExceeded", Text("big integer: limit exceeded")),
        ],
        "BinaryError" => &[
            ("InvalidInput", Text("binary: invalid input")),
            ("OutOfRange", Text("binary: value out of range")),
        ],
        "CollectionError" => &[
            ("InvalidInput", Text("collection: invalid input")),
            ("LimitExceeded", Text("collection: limit exceeded")),
            ("OutOfRange", Text("collection: value out of range")),
        ],
        "CompressionError" => &[
            ("InvalidInput", Text("compression: invalid input")),
            ("InvalidData", Text("compression: invalid data")),
            ("LimitExceeded", Text("compression: limit exceeded")),
            ("Unsupported", Text("compression: operation not supported")),
            ("Failed", Payload),
        ],
        "CryptoError" => &[
            ("InvalidInput", Text("cryptography: invalid input")),
            ("Unsupported", Text("cryptography: operation not supported")),
            (
                "AuthenticationFailed",
                Text("cryptography: authentication failed"),
            ),
        ],
        "FileSystemError" => &[
            ("InvalidInput", Text("filesystem: invalid input")),
            ("InvalidData", Text("filesystem: invalid data")),
            ("LimitExceeded", Text("filesystem: limit exceeded")),
            ("NotFound", Text("filesystem: file or directory not found")),
            ("AlreadyExists", Text("filesystem: already exists")),
            ("NotEmpty", Text("filesystem: directory not empty")),
            ("PermissionDenied", Text("filesystem: permission denied")),
            ("Unsupported", Text("filesystem: operation not supported")),
            ("Closed", Text("filesystem: resource is closed")),
            ("Failed", Payload),
        ],
        "HtmlError" => &[
            ("InvalidInput", Text("HTML: invalid input")),
            ("InvalidData", Text("HTML: invalid data")),
            ("LimitExceeded", Text("HTML: limit exceeded")),
        ],
        "HttpError" => &[
            ("InvalidInput", Text("HTTP: invalid input")),
            ("InvalidData", Text("HTTP: invalid data")),
            ("LimitExceeded", Text("HTTP: limit exceeded")),
            ("PermissionDenied", Text("HTTP: permission denied")),
            ("Closed", Text("HTTP: resource is closed")),
            ("Timeout", Text("HTTP: operation timed out")),
            ("Failed", Payload),
        ],
        "IoError" => &[
            ("Closed", Text("I/O: resource is closed")),
            ("InvalidInput", Text("I/O: invalid input")),
            ("Unavailable", Text("I/O: service unavailable")),
            ("InvalidData", Text("I/O: invalid data")),
            ("LimitExceeded", Text("I/O: limit exceeded")),
            ("Failed", Payload),
        ],
        "JsonError" => &[
            ("InvalidInput", Text("JSON: invalid input")),
            ("InvalidData", Text("JSON: invalid data")),
            ("LimitExceeded", Text("JSON: limit exceeded")),
        ],
        "LogError" => &[
            ("InvalidInput", Text("logging: invalid input")),
            ("InvalidData", Text("logging: invalid data")),
            ("LimitExceeded", Text("logging: limit exceeded")),
            ("Closed", Text("logging: resource is closed")),
            ("Io", Cause("IoError")),
            ("FileSystem", Cause("FileSystemError")),
        ],
        "NetworkError" => &[
            ("InvalidInput", Text("network: invalid input")),
            ("InvalidData", Text("network: invalid data")),
            ("LimitExceeded", Text("network: limit exceeded")),
            ("PermissionDenied", Text("network: permission denied")),
            ("Unsupported", Text("network: operation not supported")),
            ("Closed", Text("network: resource is closed")),
            ("Timeout", Text("network: operation timed out")),
            ("Failed", Payload),
        ],
        "NumberError" => &[
            ("InvalidInput", Text("number: invalid input")),
            ("InvalidData", Text("number: invalid data")),
            ("OutOfRange", Text("number: value out of range")),
        ],
        "PathError" => &[("InvalidInput", Text("path: invalid input"))],
        "ProcessError" => &[
            ("InvalidInput", Text("process: invalid input")),
            ("InvalidData", Text("process: invalid data")),
            ("LimitExceeded", Text("process: limit exceeded")),
            ("NotFound", Text("process: not found")),
            ("AlreadyExists", Text("process: already exists")),
            ("PermissionDenied", Text("process: permission denied")),
            ("Unsupported", Text("process: operation not supported")),
            ("Closed", Text("process: resource is closed")),
            ("Failed", Payload),
        ],
        "CommandError" => &[
            ("InvalidInput", Text("command: invalid input")),
            ("Unavailable", Text("command: service unavailable")),
            ("Timeout", Text("command: operation timed out")),
            ("OutputLimit", Text("command: output limit exceeded")),
            ("Failed", Payload),
        ],
        "RandomError" => &[
            ("InvalidInput", Text("random: invalid input")),
            ("LimitExceeded", Text("random: limit exceeded")),
            ("Failed", Payload),
        ],
        "RegexError" => &[
            ("InvalidInput", Text("regular expression: invalid input")),
            ("InvalidData", Text("regular expression: invalid data")),
            ("LimitExceeded", Text("regular expression: limit exceeded")),
        ],
        "StringError" => &[
            ("InvalidInput", Text("string: invalid input")),
            ("OutOfRange", Text("string: value out of range")),
            ("LimitExceeded", Text("string: limit exceeded")),
            ("Failed", Payload),
        ],
        "SystemError" => &[
            ("InvalidInput", Text("system: invalid input")),
            ("InvalidData", Text("system: invalid data")),
            ("LimitExceeded", Text("system: limit exceeded")),
            ("NotFound", Text("system: not found")),
            ("AlreadyExists", Text("system: already exists")),
            ("PermissionDenied", Text("system: permission denied")),
            ("Unsupported", Text("system: operation not supported")),
            ("Closed", Text("system: resource is closed")),
            ("Failed", Payload),
        ],
        "TerminalError" => &[
            ("InvalidInput", Text("terminal: invalid input")),
            (
                "NotTerminal",
                Text("terminal: standard stream is not a terminal"),
            ),
            ("Unsupported", Text("terminal: operation not supported")),
            ("Busy", Text("terminal: terminal is already in use")),
            ("Closed", Text("terminal: resource is closed")),
            ("Failed", Payload),
        ],
        "TimeError" => &[
            ("InvalidInput", Text("time: invalid input")),
            ("Closed", Text("time: resource is closed")),
            ("InvalidData", Text("time: invalid data")),
            ("OutOfRange", Text("time: value out of range")),
        ],
        "TlsError" => &[
            ("InvalidInput", Text("TLS: invalid input")),
            ("InvalidData", Text("TLS: invalid data")),
            ("LimitExceeded", Text("TLS: limit exceeded")),
            ("AuthenticationFailed", Text("TLS: authentication failed")),
        ],
        "UrlError" => &[
            ("InvalidInput", Text("URL: invalid input")),
            ("InvalidData", Text("URL: invalid data")),
            ("LimitExceeded", Text("URL: limit exceeded")),
        ],
        "WebSocketError" => &[
            ("InvalidInput", Text("WebSocket: invalid input")),
            ("InvalidData", Text("WebSocket: invalid data")),
            ("LimitExceeded", Text("WebSocket: limit exceeded")),
            ("PermissionDenied", Text("WebSocket: permission denied")),
            ("Closed", Text("WebSocket: resource is closed")),
            ("Timeout", Text("WebSocket: operation timed out")),
            ("Failed", Payload),
        ],
        _ => return None,
    })
}
