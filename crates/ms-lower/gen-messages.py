#!/usr/bin/env python3
"""Generates crates/ms-lower/src/messages.rs: the `message()` text of every standard error case.

Run from the repository root with a built Go `ms` (`make build`); the Go runtime is the source
of the texts. Cases carrying a diagnostic string (`Failed`) read their payload verbatim; cases
wrapping another error (`Io`, `FileSystem`) are left out.
"""
import glob
import os
import re
import subprocess
import tempfile

SENTINEL = "PAYLOAD-SENTINEL"
types = []
for path in sorted(glob.glob("pkg/stdlib/*.ms")):
    src = open(path).read()
    module = os.path.basename(path)
    for m in re.finditer(r"^impl Error for (\w+):\n(?:    #[^\n]*\n)*    fn message\(\) String:\s*\n(?!        )", src, re.M):
        name = m.group(1)
        tm = re.search(r"^export type " + name + r":\n((?:    .*\n|\n)*)", src, re.M)
        if not tm:
            continue
        cases = []
        body = tm.group(1)
        for c in re.finditer(r"^    case (\w+)(\(\s*(?:\s*#[^\n]*\n)*\s*(\w+): String\s*\))?", body, re.M):
            cases.append((c.group(1), c.group(3)))
        if name in ("TextError", "MissingValue") or not cases:
            continue
        types.append((module, name, cases))

prelude = set()
while True:
    prog = ['import stdout from "@std/io.ms"\n']
    for module, name, cases in types:
        if name not in prelude:
            prog.append(f'import {{{name}}} from "@std/{module}"\n')
    prog.append('\nfn say(text: String) Unit:\n    stdout().write("{text}\\n").get()\n\nexport fn main() Int:\n')
    for module, name, cases in types:
        for case, field in cases:
            if field:
                prog.append(f'    say("{name}.{case}=" + {name}.{case}({field}: "{SENTINEL}").message())\n')
            elif case in ("Io", "FileSystem"):
                continue
            else:
                prog.append(f'    say("{name}.{case}=" + {name}.{case}.message())\n')
    prog.append("    return 0\n")
    with tempfile.NamedTemporaryFile("w", suffix=".ms", delete=False) as f:
        f.write("".join(prog))
        probe = f.name
    res = subprocess.run(["./ms", "run", probe], capture_output=True, text=True)
    redundant = re.findall(r"redundant prelude import (\w+)", res.stderr)
    if redundant:
        prelude.update(redundant)
        continue
    if res.returncode:
        raise SystemExit(res.stderr)
    break
table = {}
for line in res.stdout.splitlines():
    key, _, text = line.partition("=")
    t, _, case = key.partition(".")
    table.setdefault(t, []).append((case, text))
rs = ["// Generated by crates/ms-lower/gen-messages.py from the Go runtime; do not edit.\n",
      "\nuse crate::iface::Message::{self, Payload, Text};\n\n",
      "/// The `message()` text of each case of a standard error type.\n",
      "pub(crate) fn table(name: &str) -> Option<&'static [(&'static str, Message)]> {\n",
      "    Some(match name {\n"]
for t, cases in table.items():
    rs.append(f'        "{t}" => &[\n')
    for case, text in cases:
        rendered = "Payload" if text == SENTINEL else 'Text("' + text.replace("\\", "\\\\").replace('"', '\\"') + '")'
        rs.append(f'            ("{case}", {rendered}),\n')
    rs.append("        ],\n")
rs.append("        _ => return None,\n    })\n}\n")
open("crates/ms-lower/src/messages.rs", "w").write("".join(rs))
