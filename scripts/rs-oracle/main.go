// Command rs-oracle records the behavior of the Go standard-library natives
// (pkg/runtime) as tab-separated fixtures that the Rust ms-std-* crates replay in
// their tests: `go run ./scripts/rs-oracle <module>... [-out crates]`.
//
// Each line is `<case>\t<hex-encoded inputs...>\t=>\t<result>`; strings and bytes are hex so
// that arbitrary content survives. Corpora are hand-picked plus seeded pseudo-random inputs, so
// regenerating is deterministic.
package main

import (
	"archive/tar"
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"hash/crc32"
	"io/fs"
	"math"
	"math/rand"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
	"time"

	rt "github.com/manuscript-lang/manuscript/pkg/runtime"
)

type recorder struct{ lines []string }

func (r *recorder) row(parts ...string) { r.lines = append(r.lines, strings.Join(parts, "\t")) }

func h(s string) string { return "x" + hex.EncodeToString([]byte(s)) }

func hb(b *rt.Bytes) string {
	if b == nil {
		return "x"
	}
	return "x" + hex.EncodeToString(b.Data)
}

func opt(o rt.Option[int]) string {
	if !o.Some {
		return "-"
	}
	return strconv.Itoa(o.Val)
}

func optArg(n int, set bool) rt.Option[int] {
	if !set {
		return rt.Option[int]{}
	}
	return rt.Some(n)
}

func b2s(b bool) string {
	if b {
		return "1"
	}
	return "0"
}

// errName returns the error case name of a Result error value (InvalidInput, ...).
func errName(e any) string {
	n := reflect.TypeOf(e).Name()
	return n[strings.LastIndex(n, "_")+1:]
}

func okOrErr[T, E any](r rt.Result[T, E], ok func(T) []string) []string {
	if r.Failed {
		return []string{"err", errName(r.Err)}
	}
	return append([]string{"ok"}, ok(r.Val)...)
}

func (r *recorder) write(dir, name string) {
	path := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fatal(err)
	}
	data := "# Generated by `go run ./scripts/rs-oracle`; do not edit.\n" + strings.Join(r.lines, "\n") + "\n"
	if err := os.WriteFile(path, []byte(data), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("wrote", path, len(r.lines), "cases")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

// randomStrings returns n strings of up to maxLen runes drawn from the alphabet.
func randomStrings(seed int64, n, maxLen int, alphabet []string) []string {
	rng := rand.New(rand.NewSource(seed))
	out := make([]string, n)
	for i := range out {
		var b strings.Builder
		for j, l := 0, rng.Intn(maxLen+1); j < l; j++ {
			b.WriteString(alphabet[rng.Intn(len(alphabet))])
		}
		out[i] = b.String()
	}
	return out
}

func main() {
	out := flag.String("out", "crates", "crates directory")
	flag.Parse()
	gens := map[string]func(dir string){
		"encoding": genEncoding,
		"csv":      genCsv,
		"url":      genURL,
		"path":     genPath,
		"compress": genCompress,
		"crypto":   genCrypto,
		"regex":    genRegex,
		"archive":  genArchive,
		"json":     genJSON,
		"html":     genHTML,
	}
	names := flag.Args()
	if len(names) == 0 {
		for n := range gens {
			names = append(names, n)
		}
	}
	for _, n := range names {
		g, ok := gens[n]
		if !ok {
			fatal(fmt.Errorf("unknown module %q", n))
		}
		g(filepath.Join(*out, "ms-std-"+n, "tests", "oracle"))
	}
}

// ---- encoding ----

func genEncoding(dir string) {
	r := &recorder{}
	texts := append([]string{"", "a", "ab", "abc", "abcd", "Zg==", "Zm8=", "Zm9v", "Zm9vYg==", "Zh==", "Zm9=", "-_8=", "+/8=", "Zg", "Zm9vYg", "=Zg=", "Z===", "Zm 9v", "Zm9v\n", "00ff", "00FF", "0", "zz", "0g", "dead BEEF", "é"},
		randomStrings(1, 60, 10, strings.Split("AZaz09+/-_= \n", ""))...)
	texts = append(texts, randomStrings(2, 30, 8, strings.Split("0123456789abcdefABCDEFg", ""))...)
	limits := []struct {
		n   int
		set bool
	}{{0, false}, {0, true}, {1, true}, {3, true}, {-1, true}}
	for _, t := range texts {
		for _, l := range limits {
			for _, url := range []bool{false, true} {
				res := rt.Encoding_Base64Decode(nil, t, url, optArg(l.n, l.set))
				r.row("b64dec", h(t), b2s(url), opt(optArg(l.n, l.set)), "=>", strings.Join(okOrErr(res, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
			}
			res := rt.Encoding_HexDecode(nil, t, optArg(l.n, l.set))
			r.row("hexdec", h(t), opt(optArg(l.n, l.set)), "=>", strings.Join(okOrErr(res, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
		}
	}
	for _, t := range texts {
		data := rt.NewBytes([]byte(t))
		r.row("b64enc", h(t), "0", "=>", h(rt.Encoding_Base64Encode(nil, data, false)))
		r.row("b64enc", h(t), "1", "=>", h(rt.Encoding_Base64Encode(nil, data, true)))
		r.row("hexenc", h(t), "=>", h(rt.Encoding_HexEncode(nil, data)))
		for _, le := range []bool{true, false} {
			enc := rt.Encoding_Utf16Encode(nil, t, le)
			r.row("u16enc", h(t), b2s(le), "=>", hb(enc))
			r.row("u16dec", h(t), b2s(le), "-", "=>", strings.Join(okOrErr(rt.Encoding_Utf16Decode(nil, rt.NewBytes([]byte(t)), le, rt.Option[int]{}), func(s string) []string { return []string{h(s)} }), " "))
			r.row("u16dec", hb(enc), b2s(le), "2", "=>", strings.Join(okOrErr(rt.Encoding_Utf16Decode(nil, enc, le, rt.Some(2)), func(s string) []string { return []string{h(s)} }), " "))
			r.row("u16dec", hb(enc), b2s(le), "-", "=>", strings.Join(okOrErr(rt.Encoding_Utf16Decode(nil, enc, le, rt.Option[int]{}), func(s string) []string { return []string{h(s)} }), " "))
		}
		r.row("u16dec", h(t), "1", "-1", "=>", strings.Join(okOrErr(rt.Encoding_Utf16Decode(nil, data, true, rt.Some(-1)), func(s string) []string { return []string{h(s)} }), " "))
		r.row("l1enc", h(t), "=>", strings.Join(okOrErr(rt.Encoding_Latin1Encode(nil, t), func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
		r.row("l1dec", h(t), "=>", h(rt.Encoding_Latin1Decode(nil, data)))
		r.row("asciienc", h(t), "=>", strings.Join(okOrErr(rt.Encoding_AsciiEncode(nil, t), func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
		r.row("asciidec", h(t), "=>", strings.Join(okOrErr(rt.Encoding_AsciiDecode(nil, data), func(s string) []string { return []string{h(s)} }), " "))
	}
	// Raw byte inputs that are not valid UTF-8 text.
	for _, raw := range [][]byte{{0x00, 0xd8}, {0x00, 0xdc}, {0x3d, 0xd8, 0x00, 0xde}, {0x80}, {0xe9}, {0xff, 0xfe}} {
		data := rt.NewBytes(raw)
		for _, le := range []bool{true, false} {
			r.row("u16dec", hb(data), b2s(le), "-", "=>", strings.Join(okOrErr(rt.Encoding_Utf16Decode(nil, data, le, rt.Option[int]{}), func(s string) []string { return []string{h(s)} }), " "))
		}
		r.row("l1dec", hb(data), "=>", h(rt.Encoding_Latin1Decode(nil, data)))
		r.row("asciidec", hb(data), "=>", strings.Join(okOrErr(rt.Encoding_AsciiDecode(nil, data), func(s string) []string { return []string{h(s)} }), " "))
		r.row("b64enc", hb(data), "0", "=>", h(rt.Encoding_Base64Encode(nil, data, false)))
		r.row("hexenc", hb(data), "=>", h(rt.Encoding_HexEncode(nil, data)))
	}
	r.write(dir, "encoding.tsv")
}

// ---- csv ----

func cell(s string) string { return h(s) }

func rowsText(rows *rt.List[*rt.List[string]]) string {
	var parts []string
	for _, row := range rows.Items {
		var cells []string
		for _, c := range row.Items {
			cells = append(cells, cell(c))
		}
		parts = append(parts, "["+strings.Join(cells, ",")+"]")
	}
	return strings.Join(parts, "")
}

func genCsv(dir string) {
	r := &recorder{}
	alpha := []string{"a", "b", "1", ",", ",", "\"", "\"", "\n", "\n", "\r", "\r\n", " ", ";", "é", "\\."}
	inputs := append([]string{"", "a", "a,b\nc,d\n", "\"a,b\",c", "\"a\"\"b\"", "\"\"", "\n\n", "a\r\nb\r\n", "\"x\ny\",z\n", "a\rb", "\"a\"b", "a\"b", "\"abc", " \"a\"", "a,\n", ",\n", "\"\"\"\"\n"},
		randomStrings(3, 90, 14, alpha)...)
	opts := []struct{ delim, ending string }{{",", "\n"}, {";", "\r\n"}, {"\t", "\n"}, {"", "\n"}, {",,", "\n"}, {"\"", "\n"}, {",", "\r"}, {"\n", "\n"}}
	for _, in := range inputs {
		for _, o := range opts[:4] {
			for _, lim := range [][2]rt.Option[int]{{{}, {}}, {rt.Some(1), {}}, {{}, rt.Some(2)}, {rt.Some(-1), {}}} {
				res := rt.Csv_Parse(nil, in, &rt.CsvOptions{Delimiter: o.delim, LineEnding: o.ending}, lim[0], lim[1])
				r.row("parse", h(in), h(o.delim), h(o.ending), opt(lim[0]), opt(lim[1]), "=>", strings.Join(okOrErr(res, func(l *rt.List[*rt.List[string]]) []string { return []string{rowsText(l)} }), " "))
			}
		}
	}
	for _, o := range opts[4:] {
		res := rt.Csv_Parse(nil, "a", &rt.CsvOptions{Delimiter: o.delim, LineEnding: o.ending}, rt.Option[int]{}, rt.Option[int]{})
		r.row("parse", h("a"), h(o.delim), h(o.ending), "-", "-", "=>", strings.Join(okOrErr(res, func(l *rt.List[*rt.List[string]]) []string { return []string{rowsText(l)} }), " "))
	}
	// Stringify random tables.
	rng := rand.New(rand.NewSource(4))
	cells := randomStrings(5, 200, 6, alpha)
	for i := 0; i < 70; i++ {
		var rows []*rt.List[string]
		for j, n := 0, rng.Intn(4); j < n; j++ {
			var row []string
			for k, m := 0, rng.Intn(4); k < m; k++ {
				row = append(row, cells[rng.Intn(len(cells))])
			}
			rows = append(rows, rt.NewList(row...))
		}
		list := rt.NewList(rows...)
		for _, o := range opts[:4] {
			for _, lim := range []rt.Option[int]{{}, rt.Some(5), rt.Some(0), rt.Some(-1), rt.Some(20)} {
				res := rt.Csv_Stringify(nil, list, &rt.CsvOptions{Delimiter: o.delim, LineEnding: o.ending}, lim)
				r.row("stringify", rowsText(list), h(o.delim), h(o.ending), opt(lim), "=>", strings.Join(okOrErr(res, func(s string) []string { return []string{h(s)} }), " "))
			}
		}
	}
	r.write(dir, "csv.tsv")
}

// ---- url ----

func urlText(u *rt.Url) string {
	return strings.Join([]string{h(u.Scheme), h(u.Host), opt(u.Port), h(u.Path), h(u.Query), h(u.Fragment)}, " ")
}

func queryText(l *rt.List[*rt.QueryEntry]) string {
	var parts []string
	for _, e := range l.Items {
		parts = append(parts, h(e.Key)+":"+h(e.Value))
	}
	return "[" + strings.Join(parts, ",") + "]"
}

func genURL(dir string) {
	r := &recorder{}
	alpha := []string{"http", "https", "ftp", ":", "//", "/", "?", "#", "@", "a", "B", "1", "%20", "%2F", "%zz", "%", ".", "..", "[", "]", "::1", " ", "&", "=", "+", "é", "-", ":80", "~"}
	inputs := append([]string{"http://example.com", "HTTP://EXAMPLE.com:8080/a/b?c=d#e", "http://[::1]:80/x", "http://[fe80::1%25eth0]/", "mailto:a@b.c", "/rel", "//host/p", "file:///etc/passwd", "http://u:p@h/", "http://h:99999", "http://h:", "http://h:1:2", "http://a b", "http://h/%zz", "http://h/%E9", "http://h/%C3%A9?x=%E9", "x:y", "1x://h", "http://h?", "http://h/p?", "a:b:c", "http://h/a%2Fb", "http://%41/", "http://h/#%zz", "http://h/#a b", "https://h/p;q?r", "ws://h:0", "http://h:65535", "http://h:65536", "http://ex\u00e9mple.com/", "http://H%C3%89/"},
		randomStrings(6, 200, 12, alpha)...)
	for _, in := range inputs {
		res := rt.Url_Parse(nil, in)
		r.row("parse", h(in), "=>", strings.Join(okOrErr(res, func(u *rt.Url) []string { return []string{urlText(u)} }), " "))
		if !res.Failed {
			u := res.Val
			fr := rt.Url_Format(nil, u)
			r.row("format", urlText(u), "=>", strings.Join(okOrErr(fr, func(s string) []string { return []string{h(s)} }), " "))
			for _, ref := range []string{"g", "./g", "../g", "/g", "//g", "?y", "#s", "", "g?y#s", "../../../g", "http://x/y", "mailto:q", "%zz", "a:b", "//u@h/", "."} {
				rr := rt.Url_Resolve(nil, u, ref)
				r.row("resolve", urlText(u), h(ref), "=>", strings.Join(okOrErr(rr, func(u *rt.Url) []string { return []string{urlText(u)} }), " "))
			}
		}
	}
	// Format from arbitrary components.
	rng := rand.New(rand.NewSource(7))
	comp := randomStrings(8, 120, 8, alpha)
	for i := 0; i < 500; i++ {
		pick := func() string { return comp[rng.Intn(len(comp))] }
		u := &rt.Url{Scheme: []string{"http", "https", "HTTP", "", "x-y", "1a"}[rng.Intn(6)], Host: []string{"h", "example.com", "", "::1", "a b", "h:1", "H"}[rng.Intn(7)], Path: pick(), Query: pick(), Fragment: pick()}
		if rng.Intn(2) == 0 {
			u.Port = rt.Some([]int{0, 80, 65535, 65536, -1}[rng.Intn(5)])
		}
		fr := rt.Url_Format(nil, u)
		r.row("format", urlText(u), "=>", strings.Join(okOrErr(fr, func(s string) []string { return []string{h(s)} }), " "))
	}
	// Components and queries.
	for _, in := range append(inputs[:60], "a b", "é", "~-._", "100%", "+") {
		r.row("encode", h(in), "=>", h(rt.Url_EncodeComponent(nil, in)))
		r.row("decode", h(in), "=>", strings.Join(okOrErr(rt.Url_DecodeComponent(nil, in), func(s string) []string { return []string{h(s)} }), " "))
	}
	qalpha := []string{"a", "b", "=", "&", "&", "+", "%20", "%zz", "%", "é", ";", "1", "%E9"}
	for _, in := range append([]string{"", "a=1&b=2&a=3", "&&", "a", "=", "=v", "k=", "a%20b=c+d", "a=%", "a=1;b=2"}, randomStrings(9, 100, 10, qalpha)...) {
		for _, lim := range []rt.Option[int]{{}, rt.Some(1), rt.Some(0), rt.Some(-1)} {
			res := rt.Url_ParseQuery(nil, in, lim)
			r.row("query", h(in), opt(lim), "=>", strings.Join(okOrErr(res, func(l *rt.List[*rt.QueryEntry]) []string { return []string{queryText(l)} }), " "))
			if !res.Failed {
				r.row("fquery", queryText(res.Val), "=>", h(rt.Url_FormatQuery(nil, res.Val)))
			}
		}
	}
	r.write(dir, "url.tsv")
}

// ---- path ----

func partsText(p *rt.PathParts) string {
	return strings.Join([]string{h(p.Root), h(p.Directory), h(p.Base), h(p.Extension), h(p.Name)}, " ")
}

func listText(items []string) string {
	hs := make([]string, len(items))
	for i, it := range items {
		hs[i] = h(it)
	}
	return "[" + strings.Join(hs, ",") + "]"
}

func genPath(dir string) {
	r := &recorder{}
	alpha := []string{"a", "b", "c", ".", "..", ".", "/", "/", "\\", "C:", "c:", "//", "srv", "share", ".txt", ".tar", ".gz", " ", "é", "x"}
	inputs := append([]string{"", ".", "..", "/", "//", "a", "a/", "/a", "a/b/c", "/a/b/c/", "a//b", "./a", "../a", "a/..", "a/../..", "/..", "C:", "C:\\", "C:\\a\\b", "C:a", "c:/a/../b", "\\\\srv\\share\\a", "\\\\srv", "\\\\srv\\", "//srv/share", "//srv/share/x", ".bashrc", "a.b.c", "a/.b", "file.", "x/y.tar.gz", "./C:", "a/b.txt/"},
		randomStrings(10, 120, 8, alpha)...)
	suffixes := []string{"", ".txt", "c", "b/c", "x", ".gz", "a"}
	for _, win := range []bool{false, true} {
		ops := rt.Path_Posix(nil)
		if win {
			ops = rt.Path_Win32(nil)
		}
		w := b2s(win)
		for _, in := range inputs {
			r.row("basename", w, h(in), "=>", h(ops.Basename(nil, in)))
			for _, sfx := range suffixes {
				r.row("basename_without", w, h(in), h(sfx), "=>", h(ops.BasenameWithout(nil, in, sfx)))
			}
			r.row("dirname", w, h(in), "=>", h(ops.Dirname(nil, in)))
			r.row("extension", w, h(in), "=>", h(ops.Extension(nil, in)))
			r.row("is_absolute", w, h(in), "=>", b2s(ops.IsAbsolute(nil, in)))
			r.row("normalize", w, h(in), "=>", h(ops.Normalize(nil, in)))
			r.row("namespaced", w, h(in), "=>", h(ops.ToNamespacedPath(nil, in)))
			parts := ops.Parse(nil, in)
			r.row("parse", w, h(in), "=>", partsText(parts))
			r.row("format", w, partsText(parts), "=>", h(ops.Format(nil, parts)))
			r.row("resolve", w, h(in), "[]", "=>", strings.Join(okOrErr(ops.Resolve(nil, in, rt.NewList[string]()), func(s string) []string { return []string{h(s)} }), " "))
		}
		rng := rand.New(rand.NewSource(11))
		pick := func() string { return inputs[rng.Intn(len(inputs))] }
		for i := 0; i < 150; i++ {
			var items []string
			for j, n := 0, rng.Intn(4); j < n; j++ {
				items = append(items, pick())
			}
			r.row("join", w, listText(items), "=>", h(ops.Join(nil, rt.NewList(items...))))
			base := pick()
			r.row("resolve", w, h(base), listText(items), "=>", strings.Join(okOrErr(ops.Resolve(nil, base, rt.NewList(items...)), func(s string) []string { return []string{h(s)} }), " "))
			a, b := pick(), pick()
			r.row("relative", w, h(a), h(b), "=>", strings.Join(okOrErr(ops.Relative(nil, a, b), func(s string) []string { return []string{h(s)} }), " "))
			p := &rt.PathParts{Root: pick(), Directory: pick(), Base: []string{"", "f.txt", "g"}[rng.Intn(3)], Extension: []string{"", ".md", "md"}[rng.Intn(3)], Name: pick()}
			r.row("format", w, partsText(p), "=>", h(ops.Format(nil, p)))
		}
		globAlpha := []string{"*", "**", "?", "[a-c]", "[!a]", "[", "]", "{a,b}", "{1..3}", "{", "}", "@(a|b)", "+(a)", "!(b)", "?(a)", "*(a)", "a", "b", "c", "/", ".", "\\", "-", "(", ")", "|", "é", ".txt"}
		valAlpha := []string{"a", "b", "c", "/", ".", "1", "2", "é", ".txt", "ab"}
		gp := append([]string{"*.txt", "**/*.txt", "a/**/b", "[a-c]*", "{a,b}/c", "f{01..03}", "!(a)*", "*(ab)", "[]", "{x", "@(a", "\\", "a/[b"}, randomStrings(12, 70, 6, globAlpha)...)
		gv := append([]string{"a.txt", "a/b.txt", "a/b/c", ".hidden", "a/.h/b", "f02", "ab", ""}, randomStrings(13, 14, 7, valAlpha)...)
		for _, pat := range gp {
			for _, v := range gv {
				res := ops.MatchesGlob(nil, v, pat)
				r.row("glob", w, h(v), h(pat), "=>", strings.Join(okOrErr(res, func(b bool) []string { return []string{b2s(b)} }), " "))
			}
		}
	}
	r.write(dir, "path.tsv")
}

// ---- compress ----

func genCompress(dir string) {
	r := &recorder{}
	rng := rand.New(rand.NewSource(14))
	plains := [][]byte{{}, []byte("a"), []byte("hello hello hello"), make([]byte, 700)}
	noise := make([]byte, 500)
	rng.Read(noise)
	plains = append(plains, noise, []byte(strings.Repeat("the quick brown fox ", 30)))
	formats := []string{"gzip", "zlib", "deflate", "bz2", ""}
	for _, f := range formats {
		for _, p := range plains {
			for _, level := range []int{-1, 0, 1, 6, 9, 10} {
				res := rt.Compress_Compress(nil, rt.NewBytes(p), f, level, rt.Option[int]{})
				status := "ok"
				if res.Failed {
					status = "err " + errName(res.Err)
				}
				r.row("compress", f, strconv.Itoa(level), "-", "=>", status)
				if !res.Failed && (level == 0 || level == 6) {
					packed := res.Val.Data
					for _, lim := range []rt.Option[int]{{}, rt.Some(len(p)), rt.Some(len(p) - 1), rt.Some(0), rt.Some(-1)} {
						d := rt.Compress_Decompress(nil, rt.NewBytes(packed), f, lim)
						r.row("decompress", f, hb(rt.NewBytes(packed)), opt(lim), "=>", strings.Join(okOrErr(d, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
					}
					// Corrupted variants of the Go-produced stream.
					variants := [][]byte{packed[:len(packed)/2], append(append([]byte{}, packed...), 0), append(append([]byte{}, packed...), packed...)}
					for i := 0; i < 4 && len(packed) > 0; i++ {
						v := append([]byte{}, packed...)
						v[rng.Intn(len(v))] ^= byte(1 << uint(rng.Intn(8)))
						variants = append(variants, v)
					}
					for _, v := range variants {
						d := rt.Compress_Decompress(nil, rt.NewBytes(v), f, rt.Option[int]{})
						r.row("decompress", f, hb(rt.NewBytes(v)), "-", "=>", strings.Join(okOrErr(d, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
					}
				}
			}
		}
	}
	for _, f := range []string{"gzip", "zlib", "deflate"} {
		d := rt.Compress_Decompress(nil, rt.NewBytes([]byte("not compressed")), f, rt.Option[int]{})
		r.row("decompress", f, h("not compressed"), "-", "=>", strings.Join(okOrErr(d, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
		d = rt.Compress_Decompress(nil, rt.NewBytes(nil), f, rt.Option[int]{})
		r.row("decompress", f, "x", "-", "=>", strings.Join(okOrErr(d, func(b *rt.Bytes) []string { return []string{hb(b)} }), " "))
	}
	r.write(dir, "compress.tsv")
}

