// bench-flat-literals emits actual source/compiler workloads without including
// checking or process startup in the runtime benchmark loop.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/manuscript-lang/manuscript/pkg/compiler"
)

func main() {
	output := flag.String("output", ".artifacts/flat-literals/current", "output directory")
	sizes := flag.String("sizes", "1000,4000,16000,100000", "comma-separated literal sizes")
	effectful := flag.Bool("effectful", false, "evaluate a source call for each element")
	flag.Parse()
	for _, size := range strings.Split(*sizes, ",") {
		n, err := strconv.Atoi(size)
		if err != nil || n <= 0 {
			panic("sizes must contain positive integers")
		}
		var source strings.Builder
		source.WriteString("import List from \"@std/collections.ms\"\n")
		if *effectful {
			source.WriteString("type Counter:\n    value: Int\nfn tick(counter: Counter) -> Int:\n    counter.value = counter.value + 1\n    return counter.value\n")
		}
		source.WriteString("fn values() -> List[Int]:\n")
		if *effectful {
			source.WriteString("    let counter = Counter(0)\n")
		}
		source.WriteString("    return [")
		for i := 0; i < n; i++ {
			if i != 0 {
				source.WriteString(", ")
			}
			if *effectful {
				source.WriteString("tick(counter)")
			} else {
				source.WriteString(strconv.Itoa(i))
			}
		}
		fmt.Fprintf(&source, "]\nexport fn main() -> Int:\n    return values().length() - %d\n", n)
		result := compiler.CompileSource("flat.ms", source.String(), compiler.Options{Entry: true})
		if !result.Success() {
			panic(result.Diagnostics)
		}
		symbol := result.Program.Symbols["flat.ms"]["values"]
		first := 0
		if *effectful {
			first = 1
		}
		harness := fmt.Sprintf(`package main
import("testing"; rt "github.com/manuscript-lang/manuscript/pkg/runtime")
var sink rt.Value
func TestResult(t *testing.T) {
    initialize()
    result := rt.Invoke(rt.RootExecution(), %s, nil).(*rt.List)
    if len(result.Items) != %d {t.Fatal(len(result.Items))}
    for i, item := range result.Items {
        if rt.IntValue(item) != int64(i + %d) {t.Fatalf("element %%d = %%v", i, item)}
    }
}
func BenchmarkLiteral(b *testing.B) {
    initialize()
    ctx := rt.RootExecution()
    b.ReportAllocs()
    b.ResetTimer()
    for i := 0; i < b.N; i++ {sink = rt.Invoke(ctx, %s, nil)}
}
`, symbol.ID, n, first, symbol.ID)
		dir := filepath.Join(*output, strconv.Itoa(n))
		if err := os.MkdirAll(dir, 0755); err != nil {
			panic(err)
		}
		for name, data := range map[string]string{"source.ms": source.String(), "program.go": result.Source, "program_test.go": harness} {
			if err := os.WriteFile(filepath.Join(dir, name), []byte(data), 0644); err != nil {
				panic(err)
			}
		}
		fmt.Printf("%s: %d elements, %d generated bytes\n", dir, n, len(result.Source))
	}
}
